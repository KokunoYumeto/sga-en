def unique_spans(hits):
    spans={}
    for a,b,kind in hits:
        spans[a,b]=kind if (a,b) not in spans else 'same physical span'
    return [(a,b,kind) for (a,b),kind in spans.items()]

def main():
    data=json.loads((ROOT/'work_fr/initial_layers.json').read_text())
    scope=json.loads((ROOT/'work_fr/mp_t12_audit_scope.json').read_text())
    files={p['expose']:p['file'] for p in json.loads((ROOT/'sources/api_pass_20261111/PAGES.json').read_text())}
    rows=[]
    for z in scope:
        ident=z['id'];rec=z['record'];f=files[rec['expose']];page=rec['page']
        if ident not in PAIRS:continue
        for j,(printed,corrected) in enumerate(PAIRS[ident],1):
            printed=printed.replace(r'\prime',"'");corrected=corrected.replace(r'\prime',"'")
            assert printed!=corrected,(ident,j,'collapsed readings')
            row={'id':ident,'part':j,'file':f,'page':page,'expose':rec['expose'],'printed':printed,'corrected':corrected,'source':f'fixes/MISPRINTS_4.json#{ident}','reason':rec['note'],'place':rec['where']}
            if r'\sisi' in rec.get('tex_did',''):row['represented_by_human_record']=True
            if ident=='MP0464':row['placement_note']='The visible heading is generated by the counter. A local thesubsubsection override restores 7.2.1 only for this diplomatic heading; the global counter increment and link anchor are retained.'
            for layer,target in [('dip',printed),('corr',corrected)]:
                text=data[layer][f];hits=locate(text,printed,corrected,page)
                if not hits and (ident,j) in INTERMEDIATE:hits=[(a,b,'source editorial reading') for a,b in find_exact(text,INTERMEDIATE[ident,j],page)]
                if not hits:hits=locate(text,printed,corrected,None)
                hits=unique_spans(hits);row[layer+'_hits']=len(hits)
                if len(hits)==1:
                    a,b,kind=hits[0];actual=text[a:b];replacement=carry_markers(actual,target)
                    row[layer]={'old':actual,'new':replacement,'at':a,'state':kind,'context_before':text[max(0,a-90):a],'context_after':text[b:b+90]}
                    data[layer][f]=text[:a]+replacement+text[b:]
                else:row[layer]={'status':'needs-location-review'}
            rows.append(row)
    out=ROOT/'output/shared/MP_T12_AUDIT_PAIRS.json';out.write_text(json.dumps(rows,ensure_ascii=False,indent=2)+'\n')
    failed=[r for r in rows if r['dip_hits']!=1 or r['corr_hits']!=1]
    (ROOT/'work_fr/mp_t12_unlocated.json').write_text(json.dumps(failed,ensure_ascii=False,indent=2)+'\n')
    print('Scope',len(scope),'Reviewed',len(PAIRS),'Pairs',len(rows),'Unique both',len(rows)-len(failed),'Unlocated',len(failed))
    for r in failed:print(r['id'],r['part'],r['dip_hits'],r['corr_hits'])

if __name__=='__main__':main()
